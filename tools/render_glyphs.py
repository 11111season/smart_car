def render(glyph):
    assert len(glyph) == 32, f"长度 {len(glyph)} != 32"
    for row in range(16):
        b0, b1 = glyph[row * 2], glyph[row * 2 + 1]
        line = ""
        for col in range(16):
            byte = b0 if col < 8 else b1
            bit = (byte >> (7 - (col % 8))) & 0x01
            line += "██" if bit else "  "
        print(line)

if __name__ == "__main__":
    for ch, glyph in GLYPHS:
        print(f"===== {ch} =====")
        render(glyph)
