#ifndef _VL53L5CX_H_
#define _VL53L5CX_H_

#include "zf_common_typedef.h"

//====================================================软件 IIC 配置====================================================
#define VL53L5CX_USE_SOFT_IIC           ( 1 )                                       // 默认使用软件 IIC 方式驱动
#if VL53L5CX_USE_SOFT_IIC
#define VL53L5CX_SOFT_IIC_DELAY         ( 100 )                                     // 软件 IIC 延时时间 数值越小 IIC 通信速率越高
#define VL53L5CX_SCL_PIN                (P19_0)                                     // 软件 IIC SCL 引脚 接 VL53L5CX SCL
#define VL53L5CX_SDA_PIN                (P19_1)                                     // 软件 IIC SDA 引脚 接 VL53L5CX SDA
#else
#error "暂不支持硬件 IIC 通讯"
#endif
//====================================================软件 IIC 配置====================================================

//====================================================硬件控制引脚====================================================
#define VL53L5CX_PWR_EN_PIN             (P13_0)                                     // 传感器电源使能 高电平供电
#define VL53L5CX_LPn_PIN                (P13_1)                                     // 低功耗模式控制 高电平=正常工作
//====================================================硬件控制引脚====================================================

//====================================================中断引脚配置====================================================
#define VL53L5CX_INT_ENABLE             ( 0 )                                       // 是否开启 INT 中断 默认关闭使用轮询
#if VL53L5CX_INT_ENABLE
#define VL53L5CX_INT_PIN                (P13_3)                                     // INT 中断引脚
#endif
//====================================================中断引脚配置====================================================

//==================================================IIC 地址配置======================================================
#define VL53L5CX_DEV_ADDR               ( 0x29 )                                    // VL53L5CX I2C 7-bit 地址
//==================================================IIC 地址配置======================================================

//================================================定义 VL53L5CX 数据结构================================================
#define VL53L5CX_MAX_ZONES              ( 64 )

typedef struct
{
    uint16  distance_mm[VL53L5CX_MAX_ZONES];                                       // 每个区的距离值（毫米）
    uint8   status[VL53L5CX_MAX_ZONES];                                             // 每个区的状态（5或9=有效）
    uint8   zone_count;                                                             // 当前区数量（16 或 64）
}vl53l5cx_result_t;

typedef struct
{
    uint8   resolution;                                                             // 分辨率：16=4x4 64=8x8
    uint16  timing_budget_ms;                                                       // 积分时间（ms，范围2~1000）
    uint8   ranging_frequency_hz;                                                   // 测距频率（Hz）
}vl53l5cx_config_t;
//================================================定义 VL53L5CX 数据结构================================================


//================================================声明 VL53L5CX 全局变量================================================
extern uint8                vl53l5cx_init_flag;                                     // 模块完成初始化标志位
extern uint8                vl53l5cx_finsh_flag;                                    // 数据更新完成标志位
extern uint16               vl53l5cx_distance_mm;                                   // 首区（Zone 0）距离（毫米）
extern vl53l5cx_result_t    vl53l5cx_zone_result;                                   // 多区测距结果
extern vl53l5cx_config_t    vl53l5cx_config;                                        // 当前配置参数
//================================================声明 VL53L5CX 全局变量================================================


//================================================声明 VL53L5CX 基础函数================================================

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     初始化 VL53L5CX
// 参数说明     void
// 返回参数     uint8           1-初始化失败 0-初始化成功
// 使用示例     vl53l5cx_init();
// 备注信息     初始化包括 GPIO 初始化、I2C 初始化、硬件复位、固件下载、传感器探测及配置
//-------------------------------------------------------------------------------------------------------------------
uint8  vl53l5cx_init                (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     启动测距
// 参数说明     void
// 返回参数     void
// 使用示例     vl53l5cx_start_ranging();
// 备注信息     使用当前配置参数启动连续测距模式
//-------------------------------------------------------------------------------------------------------------------
void   vl53l5cx_start_ranging       (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     停止测距
// 参数说明     void
// 返回参数     void
// 使用示例     vl53l5cx_stop_ranging();
// 备注信息     停止传感器测距
//-------------------------------------------------------------------------------------------------------------------
void   vl53l5cx_stop_ranging        (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取测距数据
// 参数说明     void
// 返回参数     void
// 使用示例     vl53l5cx_get_distance();
// 备注信息     读取所有区的测距结果 更新到 vl53l5cx_zone_result
//              执行后直接查看 vl53l5cx_zone_result.distance_mm[] 获取各区距离
//-------------------------------------------------------------------------------------------------------------------
void   vl53l5cx_get_distance        (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置传感器分辨率
// 参数说明     uint8 mode      分辨率模式 VL53L5CX_RESOLUTION_4X4=16 或 VL53L5CX_RESOLUTION_8X8=64
// 返回参数     uint8           1-设置失败 0-设置成功
// 使用示例     vl53l5cx_set_resolution(VL53L5CX_RESOLUTION_4X4);
// 备注信息     需要在停止测距状态下调用
//-------------------------------------------------------------------------------------------------------------------
uint8  vl53l5cx_set_resolution      (uint8 mode);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     更新配置到传感器
// 参数说明     void
// 返回参数     uint8           1-配置失败 0-配置成功
// 使用示例     vl53l5cx_update_config();
// 备注信息     将 vl53l5cx_config 中的参数写入传感器 需在停止测距时调用
//-------------------------------------------------------------------------------------------------------------------
uint8  vl53l5cx_update_config       (void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     VL53L5CX INT 中断响应函数
// 参数说明     void
// 返回参数     void
// 使用示例     在 VL53L5CX_INT_PIN 对应的外部中断处理函数中调用
// 备注信息     中断触发后自动调用 vl53l5cx_get_distance() 读取数据
//-------------------------------------------------------------------------------------------------------------------
void   vl53l5cx_int_handler         (void);

//================================================声明 VL53L5CX 基础函数================================================

#endif
