#ifndef _ZF_DRIVER_W25Q64_H_
#define _ZF_DRIVER_W25Q64_H_

#include "zf_common_typedef.h"

// ====================================================配置====================================================
// 接线定义 (软件SPI模拟, 板级扩展引脚无硬件SPI复用)
// 模块管脚   单片机管脚
// CLK       P06_2 (SCK)
// DI        P06_3 (MOSI, 模块数据输入)
// DO        P06_4 (MISO, 模块数据输出)
// CS        P06_5 (片选, 驱动内手动控制)
// VCC       3.3V
// GND       电源地

// 引脚定义
#define W25Q64_SCK_PIN           P06_2     // SCK 引脚
#define W25Q64_MOSI_PIN          P06_3     // MOSI 引脚 (模块 DI)
#define W25Q64_MISO_PIN          P06_4     // MISO 引脚 (模块 DO)
#define W25Q64_CS_PIN            P06_5     // CS 引脚

// 软件SPI时序参数
// 注意: 库 soft_spi 的 CS 是每字节自动拉高/拉低, 对 W25Q 不可用(页编程/擦除需整条命令保持CS低)
// 因此 CS 必须由本驱动手动控制: soft_spi_init 的 cs_pin 传 SOFT_SPI_PIN_NULL
#define W25Q64_SOFT_SPI_DELAY    (5)       // 软件SPI时钟延时 (越大越慢越稳, 越小越快)
#define W25Q64_SOFT_SPI_MODE     (3)       // SPI Mode 3: CPOL=1(空闲高) + CPHA=1(第二边沿采样)

// ====================================================芯片常量====================================================
#define W25Q64_PAGE_SIZE         (256)     // 页大小 (字节)
#define W25Q64_SECTOR_SIZE       (4096)    // 扇区大小 (字节, 擦除最小单位)
#define W25Q64_BLOCK_SIZE        (65536)   // 块大小 (字节, 64KB)

// 状态寄存器
#define W25Q64_STATUS_WIP        (0x01)    // Write In Progress 忙标志

// JEDEC ID (读ID判断芯片型号)
#define W25Q64_JEDEC_ID          (0xEF4017)  // W25Q64
// 兼容型号
#define W25Q128_JEDEC_ID         (0xEF4018)  // W25Q128
#define W25Q32_JEDEC_ID          (0xEF4016)  // W25Q32
#define W25Q16_JEDEC_ID          (0xEF4015)  // W25Q16
#define W25Q80_JEDEC_ID          (0xEF4014)  // W25Q80

// ====================================================全局变量声明====================================================
// 存储设备型号 (初始化后由 w25q64_read_id 填充)
extern uint32 w25q64_chip_id;

// ====================================================函数声明====================================================
//-------------------------------------------------------------------------------------------------------------------
// 函数简介     初始化 W25Q64 (软件SPI + 读芯片ID)
// 参数说明     void
// 返回参数     uint8        1-初始化失败(读不到W25Q系列) 0-初始化成功
// 使用示例     uint8 err = w25q64_init();
// 备注信息     初始化后可通过 w25q64_chip_id 查看具体型号
//-------------------------------------------------------------------------------------------------------------------
uint8 w25q64_init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     读 JEDEC 设备ID (0x9F)
// 参数说明     void
// 返回参数     uint32       3字节设备ID, 如 W25Q64 = 0xEF4017
// 使用示例     uint32 id = w25q64_read_id();
// 备注信息     也用于上电自检: 返回 0xFFFFFF 说明没读到设备
//-------------------------------------------------------------------------------------------------------------------
uint32 w25q64_read_id(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     擦除一个扇区 (4KB)
// 参数说明     addr        扇区起始地址 (自动对齐到 4KB)
// 返回参数     void
// 使用示例     w25q64_sector_erase(0);
// 备注信息     擦除后扇区全为 0xFF
//-------------------------------------------------------------------------------------------------------------------
void w25q64_sector_erase(uint32 addr);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     擦除一个块 (64KB)
// 参数说明     addr        块起始地址 (自动对齐到 64KB)
// 返回参数     void
// 使用示例     w25q64_block_erase(0);
// 备注信息
//-------------------------------------------------------------------------------------------------------------------
void w25q64_block_erase(uint32 addr);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     整片擦除
// 参数说明     void
// 返回参数     void
// 使用示例     w25q64_chip_erase();
// 备注信息     8Mbit=1MB 全擦, 较耗时
//-------------------------------------------------------------------------------------------------------------------
void w25q64_chip_erase(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     页编程写入 (单页 ≤256 字节)
// 参数说明     buf         待写入数据
// 参数说明     addr        页内地址 (自动对齐到 256 页)
// 参数说明     len         写入字节数 (超 256 自动截断)
// 返回参数     void
// 使用示例     w25q64_page_write(data, 0x1000, 100);
// 备注信息     页内地址不能跨 256 边界, 跨页用 w25q64_write
//-------------------------------------------------------------------------------------------------------------------
void w25q64_page_write(const uint8 *buf, uint32 addr, uint16 len);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     连续写入任意长度 (自动跨页)
// 参数说明     buf         待写入数据
// 参数说明     addr        写入起始地址
// 参数说明     len         写入字节数
// 返回参数     void
// 使用示例     w25q64_write(data, 0x1000, 600);
// 备注信息     写入前必须擦除目标区域
//-------------------------------------------------------------------------------------------------------------------
void w25q64_write(const uint8 *buf, uint32 addr, uint32 len);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     连续读取任意长度
// 参数说明     buf         数据接收缓冲区
// 参数说明     addr        读取起始地址
// 参数说明     len         读取字节数
// 返回参数     void
// 使用示例     w25q64_read(rx_buf, 0x1000, 600);
// 备注信息     无需先擦除
//-------------------------------------------------------------------------------------------------------------------
void w25q64_read(uint8 *buf, uint32 addr, uint32 len);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     掉电模式
// 参数说明     void
// 返回参数     void
// 使用示例     w25q64_power_down();
// 备注信息     掉电后需 w25q64_wake_up 唤醒
//-------------------------------------------------------------------------------------------------------------------
void w25q64_power_down(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     唤醒 (退出掉电模式)
// 参数说明     void
// 返回参数     void
// 使用示例     w25q64_wake_up();
// 备注信息
//-------------------------------------------------------------------------------------------------------------------
void w25q64_wake_up(void);

#endif /* _ZF_DRIVER_W25Q64_H_ */
