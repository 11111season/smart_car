/*********************************************************************************************************************
* 函数名称       menu_show_chinese
* 功能描述       从 start_idx 起连续显示 num 个汉字
* 参数说明       x, y     起始坐标 (左上角)
*                start_idx 起始汉字索引 (见 menu_chn_idx_enum)
*                num       显示字数
*                color     前景色 RGB565
* 返回说明       无
* 使用示例       menu_show_chinese(0, 0, MENU_CHN_MAI, 6, RGB565_WHITE);  // 麦轮小车菜单
*********************************************************************************************************************/
void menu_show_chinese(uint16 x, uint16 y, menu_chn_idx_enum start_idx, uint8 num, uint16 color)
{
    if ((uint8)start_idx + num > MENU_CHN_COUNT)
    {
        return;   // 越界保护: 索引+字数超过字库总数则放弃显示
    }
    ips200_show_chinese(x, y, MENU_CHN_W, menu_font[start_idx], num, color);
}

/*********************************************************************************************************************
* 函数名称       menu_show_text
* 功能描述       按字库索引数组显示一段汉字 (支持不连续词组)
* 参数说明       x, y     起始坐标 (左上角)
*                text     字库索引数组 + 字数 (见 menu_text_t)
*                color    前景色 RGB565
* 返回说明       无
* 使用示例       menu_show_text(8, 4, &main_items[0].text, RGB565_WHITE);  // 显示菜单第1项
*********************************************************************************************************************/
void menu_show_text(uint16 x, uint16 y, const menu_text_t *text, uint16 color)
{
    uint8_t i;
    for (i = 0; i < text->num; i++)
    {
        if (text->chars[i] < MENU_CHN_COUNT)   // 越界保护: 索引超出字库总数则跳过
        {
            ips200_show_chinese(x + i*MENU_CHN_W, y, MENU_CHN_W,
                                menu_font[text->chars[i]], 1, color);
        }
    }
}
